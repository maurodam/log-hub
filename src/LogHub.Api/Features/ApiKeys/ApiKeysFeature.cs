using System.Security.Claims;
using System.Security.Cryptography;
using System.Text.Json;
using Dapper;
using LogHub.Api.Common.Security;
using LogHub.Api.Features.Ingestion;
using Npgsql;

namespace LogHub.Api.Features.ApiKeys;

public sealed record ApiKeyInput(string? Title, string[]? Permissions, string? MinimumLevel, JsonElement? AppliedProperties, bool UseServerTimestamps);

public sealed record ApiKeyDto(
    long Id,
    string Title,
    string? TokenPrefix,
    string[] Permissions,
    string? MinimumLevel,
    JsonElement AppliedProperties,
    bool UseServerTimestamps,
    bool IsDefault,
    DateTime CreatedDate);

public sealed record CreatedApiKey(ApiKeyDto ApiKey, string Token);

public sealed record ApiKeyLookup(long Id, string Title);

/// <summary>
/// /api/v1/apikeys: management (Project) and a lookup for filters (Read).
/// The token is generated by the server, returned once at creation and stored as a SHA-256 hash.
/// A key cannot get permissions its creator does not have.
/// </summary>
public static class ApiKeysFeature
{
    private const string TokenAlphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

    public static RouteGroupBuilder MapApiKeys(this RouteGroupBuilder api)
    {
        var keys = api.MapGroup("/apikeys");
        keys.MapGet("/lookup", Lookup).RequireAuthorization(Policies.Read);
        keys.MapGet("/", List).RequireAuthorization(Policies.Project);
        keys.MapPost("/", Create).RequireAuthorization(Policies.Project);
        keys.MapPut("/{id:long}", Update).RequireAuthorization(Policies.Project);
        keys.MapDelete("/{id:long}", Delete).RequireAuthorization(Policies.Project);
        return api;
    }

    private static async Task<IResult> Lookup(NpgsqlDataSource dataSource, CancellationToken cancellationToken)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        return Results.Ok(await connection.QueryAsync<ApiKeyLookup>(new CommandDefinition(
            """select id, title from api_key order by lower(title)""", cancellationToken: cancellationToken)));
    }

    private static async Task<IResult> List(NpgsqlDataSource dataSource, CancellationToken cancellationToken)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        var rows = await connection.QueryAsync<ApiKeyRow>(new CommandDefinition(
            $"""{ApiKeyRow.Select} order by lower(title)""", cancellationToken: cancellationToken));
        return Results.Ok(rows.Select(row => row.ToDto()));
    }

    private static async Task<IResult> Create(ApiKeyInput input, ClaimsPrincipal user, NpgsqlDataSource dataSource, CancellationToken cancellationToken)
    {
        if (Validate(input, user, out var values) is { } error)
        {
            return error;
        }

        var token = RandomNumberGenerator.GetString(TokenAlphabet, 24);
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        var id = await connection.ExecuteScalarAsync<long>(new CommandDefinition(
            """
            insert into api_key (title, token_hash, token_prefix, permissions, minimum_level, applied_properties, use_server_timestamps, user_created_id)
            values (@Title, @tokenHash, @tokenPrefix, @Permissions, @MinimumLevel, @AppliedProperties::jsonb, @UseServerTimestamps, @userId)
            returning id
            """,
            new
            {
                values.Title,
                tokenHash = ApiKeyStore.HashToken(token),
                tokenPrefix = token[..4],
                values.Permissions,
                values.MinimumLevel,
                values.AppliedProperties,
                values.UseServerTimestamps,
                userId = user.GetUserId(),
            },
            cancellationToken: cancellationToken));

        var created = await GetAsync(connection, id, cancellationToken);
        return Results.Created($"/api/v1/apikeys/{id}", new CreatedApiKey(created!.ToDto(), token));
    }

    private static async Task<IResult> Update(
        long id, ApiKeyInput input, ClaimsPrincipal user, NpgsqlDataSource dataSource, ApiKeyStore apiKeys, CancellationToken cancellationToken)
    {
        if (Validate(input, user, out var values) is { } error)
        {
            return error;
        }

        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        var tokenHash = await connection.QuerySingleOrDefaultAsync<string?>(new CommandDefinition(
            """
            update api_key
            set title = @Title, permissions = @Permissions, minimum_level = @MinimumLevel, applied_properties = @AppliedProperties::jsonb,
                use_server_timestamps = @UseServerTimestamps, user_updated_id = @userId, user_updated_date = now()
            where id = @id
            returning coalesce(token_hash, '')
            """,
            new { id, values.Title, values.Permissions, values.MinimumLevel, values.AppliedProperties, values.UseServerTimestamps, userId = user.GetUserId() },
            cancellationToken: cancellationToken));

        if (tokenHash is null)
        {
            return Results.NotFound();
        }

        apiKeys.Evict(tokenHash);
        return Results.Ok((await GetAsync(connection, id, cancellationToken))!.ToDto());
    }

    private static async Task<IResult> Delete(long id, NpgsqlDataSource dataSource, ApiKeyStore apiKeys, CancellationToken cancellationToken)
    {
        await using var connection = await dataSource.OpenConnectionAsync(cancellationToken);
        var tokenHash = await connection.QuerySingleOrDefaultAsync<string?>(new CommandDefinition(
            """delete from api_key where id = @id returning coalesce(token_hash, '')""", new { id }, cancellationToken: cancellationToken));

        if (tokenHash is null)
        {
            return Results.NotFound();
        }

        apiKeys.Evict(tokenHash);
        return Results.NoContent();
    }

    private static IResult? Validate(ApiKeyInput input, ClaimsPrincipal user, out (string Title, string[] Permissions, string? MinimumLevel, string AppliedProperties, bool UseServerTimestamps) values)
    {
        values = default;
        var title = input.Title?.Trim();
        if (string.IsNullOrEmpty(title) || title.Length > 200)
        {
            return ApiErrors.Result(StatusCodes.Status400BadRequest, "Title is required (max 200 characters).");
        }

        var permissions = (input.Permissions ?? []).Distinct(StringComparer.Ordinal).ToArray();
        if (permissions.FirstOrDefault(p => !Permissions.All.Contains(p)) is { } unknown)
        {
            return ApiErrors.Result(StatusCodes.Status400BadRequest, $"Unknown permission '{unknown}'.");
        }

        if (permissions.FirstOrDefault(p => !user.HasPermission(p)) is { } notOwned)
        {
            return ApiErrors.Result(StatusCodes.Status403Forbidden, $"You cannot grant the '{notOwned}' permission because you do not have it.");
        }

        string? minimumLevel = null;
        if (!string.IsNullOrWhiteSpace(input.MinimumLevel))
        {
            if (LogLevels.TryRank(input.MinimumLevel) is not { } rank)
            {
                return ApiErrors.Result(StatusCodes.Status400BadRequest, $"Unknown level '{input.MinimumLevel}'.");
            }

            minimumLevel = LogLevels.Name(rank);
        }

        var applied = input.AppliedProperties;
        if (applied is { ValueKind: not (JsonValueKind.Object or JsonValueKind.Null or JsonValueKind.Undefined) })
        {
            return ApiErrors.Result(StatusCodes.Status400BadRequest, "AppliedProperties must be a JSON object.");
        }

        values = (title, permissions, minimumLevel,
            applied is { ValueKind: JsonValueKind.Object } properties ? properties.GetRawText() : "{}",
            input.UseServerTimestamps);
        return null;
    }

    private static Task<ApiKeyRow?> GetAsync(NpgsqlConnection connection, long id, CancellationToken cancellationToken) =>
        connection.QuerySingleOrDefaultAsync<ApiKeyRow>(new CommandDefinition(
            $"""{ApiKeyRow.Select} where id = @id""", new { id }, cancellationToken: cancellationToken));

    private sealed record ApiKeyRow
    {
        public const string Select = """
            select id, title, token_prefix, permissions, minimum_level, applied_properties::text as applied_properties,
                   use_server_timestamps, is_default, user_created_date as created_date
            from api_key
            """;

        public long Id { get; init; }

        public string Title { get; init; } = string.Empty;

        public string? TokenPrefix { get; init; }

        public string[] Permissions { get; init; } = [];

        public string? MinimumLevel { get; init; }

        public string AppliedProperties { get; init; } = "{}";

        public bool UseServerTimestamps { get; init; }

        public bool IsDefault { get; init; }

        public DateTime CreatedDate { get; init; }

        public ApiKeyDto ToDto() => new(Id, Title, TokenPrefix, Permissions, MinimumLevel,
            JsonSerializer.Deserialize<JsonElement>(AppliedProperties), UseServerTimestamps, IsDefault, CreatedDate);
    }
}
